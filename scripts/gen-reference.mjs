#!/usr/bin/env node
// Copies reference/constants.json and reference/announcement-lines.json into
// web/src/lib/reference.ts so the web app and the relayer bundle them without
// reaching outside web/. Never edit the output by hand.
//   node scripts/gen-reference.mjs           write it
//   node scripts/gen-reference.mjs --check   fail if it is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const out = join(root, 'web/src/lib/reference.ts');

const body = `// GENERATED by scripts/gen-reference.mjs from reference/*.json. Do not edit.
export const constants = ${JSON.stringify(read('reference/constants.json'), null, 2)} as const;

export const announcementLines = ${JSON.stringify(read('reference/announcement-lines.json'), null, 2)} as const;
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch {}
  if (current !== body) {
    console.error('web/src/lib/reference.ts is stale: run node scripts/gen-reference.mjs');
    process.exit(1);
  }
  console.log('reference.ts is up to date');
} else {
  writeFileSync(out, body);
  console.log('wrote web/src/lib/reference.ts');
}
