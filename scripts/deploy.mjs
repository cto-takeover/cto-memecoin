// Writes scripts/deploy.md: the Friday runbook (spec 6) with every command filled
// in from reference/constants.json. It prints commands only; it never holds keys.
//
//   node scripts/deploy.mjs           write scripts/deploy.md
//   node scripts/deploy.mjs --check   fail if scripts/deploy.md is stale
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { codeHashOf } from '../verify/live.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const C = JSON.parse(readFileSync(join(ROOT, 'reference/constants.json'), 'utf8'));
const OUT = join(ROOT, 'scripts/deploy.md');
const base = (whole) => (BigInt(whole) * 10n ** BigInt(C.decimals)).toString();
const commas = (n) => Number(n).toLocaleString('en-US');

const { main, demo } = C.coins;
const { ani, budi } = C.demo_accounts;
const NET = 'network-config testnet';

// Story faces from spec 6. Face ids are 1-based: bg*512 + eyes*64 + mouth*8 + extra + 1.
const ANI_FACE = { bg: 5, eyes: 1, mouth: 0, extra: 1 };
const BUDI_FACE = { bg: 1, eyes: 2, mouth: 3, extra: 7 };
const faceId = (f) => f.bg * C.face_parts.eyes * C.face_parts.mouth * C.face_parts.extra + f.eyes * C.face_parts.mouth * C.face_parts.extra + f.mouth * C.face_parts.extra + f.extra + 1;
if (faceId(ANI_FACE) !== 2626 || faceId(BUDI_FACE) !== 672) throw new Error('story face ids changed');

const initArgs = (coin) =>
  JSON.stringify({
    name: coin.name,
    symbol: coin.symbol,
    opening_price: base(C.opening_price),
    decay_delay_s: coin.decay_delay_s,
    decay_length_s: coin.decay_length_s,
    faucet_amount: base(C.faucet_amount),
    allocations: Object.entries(coin.allocations).map(([id, whole]) => [id, base(whole)]),
  });

const wasm = join(ROOT, 'res/cto.wasm');
const wasmLine = existsSync(wasm)
  ? `Committed \`res/cto.wasm\`: SHA-256 \`${createHash('sha256').update(readFileSync(wasm)).digest('hex')}\`, NEAR code hash \`${codeHashOf(wasm)}\`.`
  : '`res/cto.wasm` is not committed yet.';

const deploySection = (coin, label) => `### ${label}: \`${coin.account}\`

1. Deploy the code and call \`new\` in one transaction. The temporary key signs it:
   \`\`\`bash
   near contract deploy ${coin.account} use-file res/cto.wasm \\
     with-init-call new json-args '${initArgs(coin)}' \\
     prepaid-gas '100 Tgas' attached-deposit '0 NEAR' \\
     ${NET} sign-with-legacy-keychain send
   \`\`\`
2. Read the rules on chain:
   \`\`\`bash
   near contract call-function as-read-only ${coin.account} get_config json-args '{}' ${NET} now
   \`\`\`
   Expected: name \`${coin.name}\`, symbol \`${coin.symbol}\`, opening_price \`${base(C.opening_price)}\` (${commas(C.opening_price)} CTO), decay_delay_s \`${coin.decay_delay_s}\`, decay_length_s \`${coin.decay_length_s}\`, faucet_amount \`${base(C.faucet_amount)}\`, takeover_ratio \`${C.takeover_ratio.num}/${C.takeover_ratio.den}\`, payout_ratio \`${C.payout_ratio_of_payment.num}/${C.payout_ratio_of_payment.den}\`.

> **Warning:** The next step is permanent. After it, nobody can change ${coin.account}. Do it only if the \`get_config\` output in step 2 is correct.

3. Delete the temporary key and rename its file:
   \`\`\`bash
   near account delete-keys ${coin.account} \\
     public-keys "$(jq -r .public_key ~/.near-credentials/testnet/${coin.account}.json)" \\
     ${NET} sign-with-legacy-keychain send
   mv ~/.near-credentials/testnet/${coin.account}.json ~/.near-credentials/testnet/${coin.account}.deleted-key.json
   \`\`\`
4. List the keys:
   \`\`\`bash
   near account list-keys ${coin.account} ${NET} now
   \`\`\`
   Expected: no keys.
`;

const md = `# Deploy runbook (spec 6, Fri Nov 13)

This runbook deploys both coins, seeds the main coin, and records the proof. It is for the human who holds the testnet keys.

\`node scripts/deploy.mjs\` writes this file from \`reference/constants.json\`. Do not edit this file by hand.

**Prerequisites:**

- near-cli-rs 0.31.1 (the version from spec 0), \`jq\`, and \`openssl\`.
- The full-access keys in \`~/.near-credentials/\`. Keys stay there and in Vercel. Do not put keys into git.
- An account of your own that pays for top-ups. This account has no power over the coins. Set it:
  \`\`\`bash
  export ME=<your-account>.testnet
  \`\`\`

${wasmLine} Docker is not available on the build machine, so this is a \`non-reproducible-wasm\` build. The README tells readers this. \`npm run verify\` compares the deployed code hash with this file.

## 1. Check the wasm

1. Get the latest code and install the dependencies:
   \`\`\`bash
   git pull && npm ci && npm --prefix web ci
   \`\`\`
2. Run the checks:
   \`\`\`bash
   npm run verify
   \`\`\`
   Expected: the Rust lines show PASS. The live lines show SKIP, because the coins are not deployed yet.

## 2. Check the accounts

\`spike/RUN.md\` created ${main.account}, ${demo.account}, ${ani} and ${budi} with the faucet on Nov 10. Each account got 10 NEAR and one full-access key. The keys are in your legacy keychain.

1. Make sure that each account has exactly one key and no code:
   \`\`\`bash
   for a in ${main.account} ${demo.account} ${ani} ${budi}; do
     ls ~/.near-credentials/testnet/$a.json && near account list-keys $a ${NET} now
   done
   \`\`\`
   If a key file is missing, the account cannot deploy. Stop and tell Claude.
2. Send 10 NEAR to ani and to budi, so each has 20 NEAR. Each takeover attaches ${C.take_seat_attached_near} NEAR for the voice key.
   \`\`\`bash
   for a in ${ani} ${budi}; do
     near tokens $ME send-near $a '10 NEAR' ${NET} sign-with-legacy-keychain send
   done
   \`\`\`

## 3. Deploy both coins

${deploySection(main, 'Main coin')}
${deploySection(demo, 'Demo coin')}
### Check both coins

Run the live checks:

\`\`\`bash
npm run verify:live
\`\`\`

Expected: 0 full-access keys on both coins, and the code hash, config, and supply all PASS.

## 4. Check Vercel (demo relayer and app)

The Vercel setup was done on Wed Nov 11 from the CLI:

- Project \`cto-memecoin\`, root directory \`web\`, Node 26.
- Production secrets \`ANI_FULL_KEY\`, \`BUDI_FULL_KEY\` and \`VOICE_SECRET\`, added from the key files.
- Live at https://ctotimes.xyz. https://cto-memecoin.vercel.app also works.
- Domain at Hostinger: A \`@\` → Vercel, CNAME \`www\` → Vercel. \`www\` redirects to the apex.
- \`.vercelignore\` uploads only the files that the build reads.
- The project is connected to GitHub. Each push to \`main\` redeploys production.

> **Warning:** Do not change \`VOICE_SECRET\`. The relayer derives the demo coin's voice keys from it. If it changes, the demo CEO cannot post.

After step 3, make sure that the app uses the deployed coins:

1. List the secrets:
   \`\`\`bash
   npx vercel@65.14.0 env ls
   \`\`\`
   Expected: the three secrets, in Production.
2. List the deployments:
   \`\`\`bash
   npx vercel@65.14.0 ls cto-memecoin
   \`\`\`
   Expected: the latest deployment from \`main\` is Ready.
3. Read the relayer state:
   \`\`\`bash
   curl -s https://ctotimes.xyz/api/demo/state | head -c 300
   \`\`\`
   Expected: the balances of ani and budi, and the seat.
4. Open the app in a private window.
   Expected: the demo coin's Front page shows SEAT OPEN. Receipts shows full-access keys 0.

## 5. Seed the story on the main coin

1. Claim the faucet for ani and budi (${commas(C.faucet_amount)} CTO each). The first claim also registers storage.
   \`\`\`bash
   for a in ${ani} ${budi}; do
     near contract call-function as-transaction ${main.account} claim_faucet json-args '{}' \\
       prepaid-gas '30 Tgas' attached-deposit '${C.storage_deposit_near} NEAR' \\
       sign-as $a ${NET} sign-with-legacy-keychain send
   done
   \`\`\`
2. Make ani's voice key for the main coin. The key stays on your machine. Keep the file.
   \`\`\`bash
   mkdir -p ~/.cto-keys/ani-main
   near account create-account fund-later use-auto-generation save-to-folder ~/.cto-keys/ani-main
   mv ~/.cto-keys/ani-main/*.json ~/.cto-keys/ani-main.json
   export ANI_VOICE=$(jq -r .public_key ~/.cto-keys/ani-main.json)
   \`\`\`
3. As ani, take the empty seat for ${commas(C.story_numbers.ani_pays_vacant)} CTO with face #${faceId(ANI_FACE)} (batik / laser / grin / CEO tie):
   \`\`\`bash
   near contract call-function as-transaction ${main.account} take_seat \\
     json-args "{\\"face\\":${JSON.stringify(ANI_FACE).replace(/"/g, '\\"')},\\"new_ceo_key\\":\\"$ANI_VOICE\\",\\"max_price\\":\\"${base(C.story_numbers.ani_pays_vacant)}\\"}" \\
     prepaid-gas '100 Tgas' attached-deposit '${C.take_seat_attached_near} NEAR' \\
     sign-as ${ani} ${NET} sign-with-legacy-keychain send
   \`\`\`
4. Post line 1 as the coin. Sign with ani's voice key:
   \`\`\`bash
   near contract call-function as-transaction ${main.account} announce json-args '{"line":1}' \\
     prepaid-gas '30 Tgas' attached-deposit '0 NEAR' \\
     sign-as ${main.account} ${NET} sign-with-access-key-file ~/.cto-keys/ani-main.json send
   \`\`\`
   Expected: the announcement reads "The face is mine until someone pays ${commas(C.story_numbers.budi_pays)} CTO."
5. List the keys:
   \`\`\`bash
   near account list-keys ${main.account} ${NET} now
   \`\`\`
   Expected: exactly one key. It is ani's voice key, and it can only call \`announce\`.

> **Note:** Stop after step 5. Budi's takeover (face #${faceId(BUDI_FACE)}, \`${JSON.stringify(BUDI_FACE)}\`) is for the video.

## 6. Record the proof

1. Run the checks and write the output to \`web/public/verify.txt\` and \`README.md\`:
   \`\`\`bash
   npm run verify -- --out web/public/verify.txt --readme
   \`\`\`
   Expected: 12 PASS.
2. Commit and push the output. Vercel redeploys, and Receipts shows the new output.
   \`\`\`bash
   git add web/public/verify.txt README.md && git commit -m "Verify output after deploy" && git push
   \`\`\`
3. Run the end-to-end tests against the deployed app:
   \`\`\`bash
   E2E_BASE_URL=https://ctotimes.xyz npm run test:e2e
   \`\`\`
4. Start the testnet end-to-end run in CI:
   \`\`\`bash
   gh workflow run ci.yml -f e2e_base_url=https://ctotimes.xyz
   \`\`\`

## Film the video on the demo coin (Sat Nov 14)

Film scenes 2–6 of \`docs/video-script.md\` on **${demo.account}**. Use a private window with no wallet. "Play as" signs for ani and budi through the relayer.

1. Wait until nobody has taken the demo seat for ${(demo.decay_delay_s + demo.decay_length_s) / 60} minutes. This includes e2e runs.
   The price is back at the floor, ${commas(C.opening_price)} CTO.
2. Play as ani. Take the seat with face #${commas(faceId(ANI_FACE))} (batik / laser / grin / CEO tie).
3. As ani, post a line as the coin. Film the Front page (scene 2).
4. Within ${demo.decay_delay_s / 60} minutes of ani's takeover, play as budi. After ${demo.decay_delay_s / 60} minutes, the price starts to fall.
5. As budi, select face #${faceId(BUDI_FACE)} part by part and press TAKE THE SEAT (scenes 3 and 4).
   Budi pays ${commas(C.story_numbers.budi_pays)}. Ani gets +${commas(C.story_numbers.ani_payout)}.
6. In the Press office, press TRY POSTING AS ani. Film NEAR's error and the REJECTED BY NEAR stamp (scene 5).
7. Film Receipts (scene 6).

> **Note:** The total burned and the supply on screen are the demo coin's real totals. They will not read 1,250,000 / 998,750,000, so the voiceover does not say them.

If a take goes wrong, wait ${(demo.decay_delay_s + demo.decay_length_s) / 60} minutes with no takeover and start again.
`;

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== md) {
    console.error('scripts/deploy.md is stale: run node scripts/deploy.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, md);
  console.log('wrote scripts/deploy.md');
}
