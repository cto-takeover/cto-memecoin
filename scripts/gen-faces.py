#!/usr/bin/env python3
"""Generates web/src/lib/faces.ts from reference/faces/faces.py.

The part strings come straight from faces.py's own functions; the assembly matches
the contract's face.rs (faces.face(uid='') with the inline style replaced by xmlns).
  python3 scripts/gen-faces.py           write it
  python3 scripts/gen-faces.py --check   fail if it is stale
"""
import json, os, sys
sys.dont_write_bytecode = True

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'reference', 'faces'))
import faces  # noqa: E402

OUT = os.path.join(ROOT, 'web', 'src', 'lib', 'faces.ts')
R = range(8)
data = {
    'bgNames': faces.BG_NAMES,
    'eyeNames': faces.EYE_NAMES,
    'mouthNames': faces.MOUTH_NAMES,
    'extraNames': faces.EXTRA_NAMES,
    'bg': [faces.bg(i, '') for i in R],
    'eyes': [faces.eyes(i) for i in R],
    'mouth': [faces.mouth(i) for i in R],
    'extra': [faces.extra(i) for i in R],
    'head': '<circle cx="100" cy="108" r="66" fill="#FFF6E0" stroke="#111111" stroke-width="6"></circle>',
}
# The head string is inlined in faces.face(); make sure ours is the same one.
assert data['head'] in faces.face(0, 0, 0, 0, uid=''), 'head circle changed in faces.py'

def ts(name, value):
    return f'export const {name} = {json.dumps(value, indent=2, ensure_ascii=False)} as const;\n'

body = (
    '// GENERATED by scripts/gen-faces.py from reference/faces/faces.py. Do not edit.\n'
    '// Assembly matches the contract (contract/src/face.rs): faceSvg(f) === face_svg(f).\n\n'
    + ''.join(ts(k, data[k]) for k in ['bgNames', 'eyeNames', 'mouthNames', 'extraNames'])
    + '\nconst PARTS = ' + json.dumps({k: data[k] for k in ['bg', 'eyes', 'mouth', 'extra', 'head']}, indent=2) + ' as const;\n'
    + '''
export interface Face {
  bg: number;
  eyes: number;
  mouth: number;
  extra: number;
}

export const PART_KEYS = ['bg', 'eyes', 'mouth', 'extra'] as const;
export type PartKey = (typeof PART_KEYS)[number];
export const PART_NAMES: Record<PartKey, readonly string[]> = { bg: bgNames, eyes: eyeNames, mouth: mouthNames, extra: extraNames };

/** bg*512 + eyes*64 + mouth*8 + extra + 1, so 1-4,096. */
export const faceId = (f: Face) => f.bg * 512 + f.eyes * 64 + f.mouth * 8 + f.extra + 1;

export function faceFromId(id: number): Face {
  const n = id - 1;
  return { bg: Math.floor(n / 512), eyes: Math.floor(n / 64) % 8, mouth: Math.floor(n / 8) % 8, extra: n % 8 };
}

export const faceLabel = (f: Face) =>
  `Coin face: ${bgNames[f.bg]}, ${eyeNames[f.eyes]} eyes, ${mouthNames[f.mouth]} mouth, ${extraNames[f.extra]}`;

/** Plain words for captions: "batik kawung · laser eyes · grin · CEO tie". */
export const faceWords = (f: Face) =>
  [bgNames[f.bg], `${eyeNames[f.eyes]} eyes`, mouthNames[f.mouth], f.extra ? extraNames[f.extra] : 'no extra'].join(' · ');

/** The same SVG string as the contract's face_svg. */
export function faceSvg(f: Face): string {
  return `<svg viewBox="0 0 200 200" width="200" height="200" role="img" aria-label="${faceLabel(f)}" xmlns="http://www.w3.org/2000/svg">${PARTS.bg[f.bg]}${PARTS.head}${PARTS.mouth[f.mouth]}${PARTS.eyes[f.eyes]}${PARTS.extra[f.extra]}</svg>`;
}

/** A data URI for <img src>, so pattern ids never collide between faces on one page. */
export function faceDataUri(f: Face): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(faceSvg(f))}`;
}
''')

if '--check' in sys.argv:
    current = open(OUT).read() if os.path.exists(OUT) else ''
    if current != body:
        sys.exit('web/src/lib/faces.ts is stale: run python3 scripts/gen-faces.py')
    print('faces.ts is up to date')
else:
    open(OUT, 'w').write(body)
    print('wrote web/src/lib/faces.ts')
